// =====================================================================
//  telemetry.h — ส่งข้อมูลสดทาง UDP พอร์ต 4210 (เร็ว, latency ต่ำ)
//
//  โปรโตคอล (ข้อความ JSON 1 แพ็กเก็ต = 1 ข้อความ):
//   เครื่องรับ -> นาฬิกา :  "hello"  หรือ  "hello t=<unix> w=1 id=studio"
//        ส่งซ้ำทุก ~2 s ให้นาฬิการู้ว่ายังมีคนรับอยู่ (เงียบ 10 s = เลิกส่ง)
//        t = เวลาจริงจากคอม (นาฬิกาไม่มี RTC) , w = 0/1 ขอคลื่น PPG ไหม
//   นาฬิกา -> เครื่องรับ:
//        {"t":"hi",...}  ตอบรับ hello ครั้งแรก (ข้อมูลเครื่อง)
//        {"t":"v",...}   ค่าที่วัดได้ 5 ครั้ง/วินาที (ECO: 2 ครั้ง/วินาที)
//        {"t":"w",...}   คลื่น PPG 10 จุด, 10 ครั้ง/วินาที
//        {"t":"e",...}   เหตุการณ์ (ผลคำถาม, กดปุ่ม, แบตต่ำ) ส่ง 2 รอบกันหาย, มี eid ไว้ตัดซ้ำ
//  ส่งแบบ unicast ถึงแต่ละเครื่อง (WiFi มี ACK/ส่งซ้ำให้) — ทดสอบแล้วหาย 0%
//  ต่างจาก broadcast ที่ไม่มี ACK และหายเยอะ
// =====================================================================
#pragma once
#include <Arduino.h>

namespace telemetry {

void task(void*);                 // telemetryTask
uint8_t clientCount();
uint32_t packetsSent();
uint32_t sendErrors();
uint32_t lastHelloMs();

}  // namespace telemetry
