// =====================================================================
//  ui.h — LED บนบอร์ด (GPIO8, PWM ด้วย LEDC) + ปุ่ม BOOT (GPIO9)
//
//  ความหมายของไฟ LED
//   ตอนเปิดเครื่อง: กระพริบ 2 ครั้ง = บูตปกติ, 4 ครั้ง = รีเซ็ตจาก watchdog/ล่ม,
//                   6 ครั้งรัว = รีเซ็ตเพราะไฟตก (brownout)
//   ติดค้าง 0.6 s หลังบูต ............. WiFi พร้อมแล้ว (ถ้ากระพริบรัว 10 ครั้ง = เปิด WiFi ไม่ได้)
//   กระพริบตามจังหวะหัวใจ ............ แตะเซนเซอร์ชีพจรอยู่ (ทำงานปกติ)
//   ติดสั้น ๆ ทุก 2 s ................ รอ (ยังไม่มีใครแตะ)
//   หายใจเข้าออกช้า ๆ ................ กำลังวัด baseline
//   ติดค้าง (หรี่) + กระพริบตามชีพจร .. กำลังถามคำถาม (12 s)
//   กระพริบรัวเร็ว 3 s ................ ผล = โกหก
//   ติดค้าง 1.5 s ..................... ผล = จริง
//   กระพริบช้า 2 ครั้ง ................ ผล = ไม่แน่ชัด
//   กระพริบสั้น 4 ครั้ง ............... ผล = ใช้ไม่ได้ (สัญญาณไม่ดี)
//   กระพริบถี่มาก ..................... กำลังอัปเดตเฟิร์มแวร์ (OTA)
//   กระพริบ 3 ครั้งซ้ำทุก 2 s ........ แบตใกล้หมด
//
//  ปุ่ม BOOT
//   กด 1 ครั้ง : ยังไม่มี baseline -> เริ่ม baseline / พร้อมแล้ว -> เริ่มคำถาม
//                กำลังถาม -> บันทึกว่า "ตอบแล้ว"
//   กด 2 ครั้ง : สลับโหมด เก็บข้อมูล (TRAIN) <-> ใช้งานจริง (DETECT)  (ไฟกระพริบ 1/2 ครั้ง)
//   กด 3 ครั้ง : LED กระพริบบอกแบต (1 ครั้ง = 20%)
//   กดค้าง 2 s : เริ่ม baseline ใหม่        (LED กระพริบ 1 ครั้งเมื่อถึง)
//   กดค้าง 5 s : Light sleep (กดอีกครั้งเพื่อปลุก)    (กระพริบ 2 ครั้ง)
//   กดค้าง 10 s: Deep sleep standby (ใส่นาฬิกาเพื่อปลุก) (กระพริบ 3 ครั้ง)
// =====================================================================
#pragma once
