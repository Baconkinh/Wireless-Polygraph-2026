// =====================================================================
//  i2c_bus.h — เริ่มบัส I2C, สแกนอุปกรณ์, และ "กู้บัสค้าง"
//
//  บัสค้างเกิดได้จริง: ถ้าไฟกระตุก/สายหลวมตอนชิปกำลังส่งบิต 0 อยู่
//  ชิปจะกด SDA ค้างไว้ตลอด -> ทุกคำสั่ง I2C ล้มเหลว
//  วิธีแก้มาตรฐาน (I2C spec): ส่ง clock 9 ลูกด้วยมือให้ชิปส่งไบต์ให้จบ แล้วส่ง STOP
// =====================================================================
#pragma once
#include <Arduino.h>

namespace i2cbus {

bool begin();                          // Wire.begin(SDA, SCL, 400k) + timeout
bool recover();                        // 9 clocks + STOP แล้วเริ่มบัสใหม่
bool probe(uint8_t addr);              // มีอุปกรณ์ตอบที่ address นี้ไหม
int  scan(uint8_t* found, int maxN);   // คืนจำนวนอุปกรณ์ที่พบ
uint32_t recoveries();                 // จำนวนครั้งที่ต้องกู้บัส (ไว้แสดงบนแดชบอร์ด)

}  // namespace i2cbus
